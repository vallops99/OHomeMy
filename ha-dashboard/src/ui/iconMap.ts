const bare = (name: string) => (name.startsWith('mdi:') ? name.slice(4) : name.includes(':') ? null : name);

/** Whether `name` has a Lucide glyph of its own, rather than the fallback. */
export function isMapped(name: string): boolean {
  const key = bare(name);
  return key !== null && key in MDI_TO_LUCIDE;
}

/**
 * The Lucide glyph for an MDI name, with or without its `mdi:` prefix. A name
 * from another set (`hass:`, `phu:`) is unmapped even when its tail matches.
 */
export function lucideFor(name: string): LucideIcon {
  const key = bare(name);
  return (key !== null && MDI_TO_LUCIDE[key]) || FALLBACK_ICON;
}
