#!/usr/bin/env python3
"""Generate the TypeScript unions of Area ids and Label ids from the manifest.

The frontend stays backend-driven at *runtime* -- an Area's contents are
always Derived from Home Assistant's registries. This generates a *dev-time
mirror* of the one thing that is fixed by the house rather than by the
registry: which Areas exist. A screen naming an Area that does not exist is a
typo, and a typo should fail `tsc` rather than render an empty cell on the
wall panel.

The manifest is already the single source of truth for the house's shape
(fake-house/README.md), so it is the right place to generate from. Run after
editing manifest.yaml's `areas`:

    python fake-house/scripts/generate-area-types.py
"""
import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "fake-house" / "manifest.yaml"
OUT = ROOT / "ha-dashboard" / "src" / "ha" / "generated" / "manifest.ts"

HEADER = """/**
 * GENERATED by fake-house/scripts/generate-area-types.py -- do not edit.
 *
 * A dev-time mirror of the Areas and Labels declared in
 * fake-house/manifest.yaml, so a screen naming one that does not exist fails
 * `tsc` instead of rendering a fault tile on the wall panel (#9).
 *
 * This does NOT make the frontend frontend-driven: Area *contents* are still
 * Derived from Home Assistant's registries at render (#3). Only the *names*
 * are mirrored, and only because they are fixed by the house rather than by
 * what is plugged in.
 *
 * Note these are the names a *screen* may compose with. `Label` in types.ts
 * stays open (`string & {}`) because an entity may carry any label a user
 * adds in Home Assistant, and the frontend must tolerate that.
 */
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the generated file is stale, without writing it",
    )
    args = parser.parse_args()

    manifest = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))
    areas = [a["id"] for a in (manifest.get("areas") or [])]
    labels = [l["id"] for l in (manifest.get("labels") or [])]
    if not areas:
        print("manifest declares no areas", file=sys.stderr)
        return 1

    def union(name: str, const: str, doc: str, ids: list[str]) -> list[str]:
        out = [f"/** {doc} */", f"export type {name} ="]
        for i, v in enumerate(ids):
            out.append(f"  | '{v}'" + (";" if i == len(ids) - 1 else ""))
        out.append("")
        joined = ", ".join(f"'{v}'" for v in ids)
        out.append(f"/** Every {name}, in manifest order. */")
        out.append(f"export const {const} = [{joined}] as const;")
        out.append("")
        return out

    lines = [HEADER]
    lines += union("KnownAreaId", "KNOWN_AREA_IDS", "An Area id declared in the manifest.", areas)
    lines += union("KnownLabel", "KNOWN_LABELS", "A Label declared in the manifest, for composing screens.", labels)

    content = "\n".join(lines)

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(
                f"{OUT.relative_to(ROOT)} is stale -- run `npm run gen:manifest`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(areas)} areas, {len(labels)} labels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
