#!/usr/bin/env python3
"""Generate Home Assistant packages from the fake-house manifest.

Reads fake-house/manifest.yaml and writes a set of YAML packages into the
Home Assistant config directory. Every entity in the manifest becomes a real
Home Assistant entity with the exact entity_id the real house will use, so
swapping fakes for real devices is a no-op on the frontend.

Each fake entity is backed by helpers that hold its state:

    input_boolean.fake_online__<slug>   availability  (off => `unavailable`)
    input_boolean.fake_state__<slug>    on/off state
    input_number.fake_level__<slug>     brightness / position
    input_select.fake_mode__<slug>      enumerated state
    input_number.fake_value__<slug>     numeric sensor value
    input_button.fake_fire__<slug>      fires an `event` entity by hand

Usage:
    python fake-house/scripts/generate.py --config-dir /path/to/ha/config
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
MANIFEST = HERE.parent / "manifest.yaml"

# Package files are written with this prefix so `clean` can remove exactly what
# this script created and nothing else.
PREFIX = "fake_"

BANNER = (
    "# GENERATED by fake-house/scripts/generate.py -- DO NOT EDIT.\n"
    "# Edit fake-house/manifest.yaml and re-run the generator.\n\n"
)


def slug(entity_id: str) -> str:
    """A helper-safe slug unique per entity (domain included).

    Home Assistant's slug validator rejects consecutive underscores, so the
    domain separator is a single underscore. Entity ids are unique across the
    house, so `light.luce_cucina` -> `light_luce_cucina` stays unique.
    """
    return entity_id.replace(".", "_")


def helper(kind: str, entity_id: str) -> str:
    # Single underscores throughout: HA's slug validator rejects `__`.
    return f"{PREFIX}{kind}_{slug(entity_id)}"


class Builder:
    def __init__(self, manifest: dict) -> None:
        self.m = manifest
        self.input_boolean: dict = {}
        self.input_number: dict = {}
        self.input_select: dict = {}
        self.input_button: dict = {}
        self.template: list = []
        self.media_player: list = []
        self.camera: list = []
        self.climate: list = []

    # -- helper plumbing -------------------------------------------------
    def online_helper(self, e: dict) -> str:
        """Every fake entity gets an availability switch, so any of them can be
        driven to `unavailable` on demand -- the design renders a visible fault."""
        name = helper("online", e["id"])
        self.input_boolean[name] = {"name": f"[online] {e['id']}", "initial": True}
        return f"input_boolean.{name}"

    def bool_helper(self, e: dict, initial: bool) -> str:
        name = helper("state", e["id"])
        self.input_boolean[name] = {"name": f"[state] {e['id']}", "initial": initial}
        return f"input_boolean.{name}"

    def num_helper(self, e: dict, kind: str, lo: float, hi: float,
                   step: float, initial: float, unit: str | None = None) -> str:
        name = helper(kind, e["id"])
        cfg = {
            "name": f"[{kind}] {e['id']}",
            "min": lo, "max": hi, "step": step, "initial": initial,
            "mode": "box",
        }
        if unit:
            cfg["unit_of_measurement"] = unit
        self.input_number[name] = cfg
        return f"input_number.{name}"

    def select_helper(self, e: dict, options: list, initial) -> str:
        name = helper("mode", e["id"])
        self.input_select[name] = {
            "name": f"[mode] {e['id']}",
            "options": [str(o) for o in options],
            "initial": str(initial),
        }
        return f"input_select.{name}"

    def fire_helper(self, e: dict) -> str:
        name = helper("fire", e["id"])
        self.input_button[name] = {"name": f"[fire] {e['id']}", "icon": "mdi:gesture-tap-button"}
        return f"input_button.{name}"

    # -- per-domain builders ---------------------------------------------
    def build(self, e: dict) -> None:
        getattr(self, f"_{e['kind']}")(e)

    def _light(self, e: dict) -> None:
        online = self.online_helper(e)
        state = self.bool_helper(e, False)
        level = self.num_helper(e, "level", 0, 255, 1, 0)
        cfg = {
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ is_state('{state}','on') }}}}",
            "level": f"{{{{ states('{level}')|int(0) }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "turn_on": {"action": "input_boolean.turn_on",
                        "target": {"entity_id": state}},
            "turn_off": {"action": "input_boolean.turn_off",
                         "target": {"entity_id": state}},
            # Setting brightness to 0 must also switch the light off, so the
            # `state` helper and the dashboard's slider never disagree.
            "set_level": [
                {"action": "input_number.set_value",
                 "target": {"entity_id": level},
                 "data": {"value": "{{ brightness }}"}},
                {"if": [{"condition": "template",
                         "value_template": "{{ brightness | int(0) > 0 }}"}],
                 "then": [{"action": "input_boolean.turn_on",
                           "target": {"entity_id": state}}],
                 "else": [{"action": "input_boolean.turn_off",
                           "target": {"entity_id": state}}]},
            ],
        }
        self.template.append({"light": [cfg]})

    def _switch(self, e: dict) -> None:
        online = self.online_helper(e)
        state = self.bool_helper(e, bool(e.get("initial") == "on"))
        self.template.append({"switch": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ is_state('{state}','on') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "turn_on": {"action": "input_boolean.turn_on",
                        "target": {"entity_id": state}},
            "turn_off": {"action": "input_boolean.turn_off",
                         "target": {"entity_id": state}},
        }]})

    def _lock(self, e: dict) -> None:
        online = self.online_helper(e)
        state = self.bool_helper(e, False)  # on == unlocked/open
        self.template.append({"lock": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ 'unlocked' if is_state('{state}','on') else 'locked' }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "lock": {"action": "input_boolean.turn_off",
                     "target": {"entity_id": state}},
            "unlock": {"action": "input_boolean.turn_on",
                       "target": {"entity_id": state}},
            "open": {"action": "input_boolean.turn_on",
                     "target": {"entity_id": state}},
        }]})

    def _alarm(self, e: dict) -> None:
        online = self.online_helper(e)
        states = ["disarmed", "armed_home", "armed_away", "armed_night",
                  "arming", "pending", "triggered"]
        mode = self.select_helper(e, states, "disarmed")
        act = lambda v: {"action": "input_select.select_option",   # noqa: E731
                         "target": {"entity_id": mode},
                         "data": {"option": v}}
        self.template.append({"alarm_control_panel": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ states('{mode}') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "code_arm_required": False,
            "disarm": act("disarmed"),
            "arm_home": act("armed_home"),
            "arm_away": act("armed_away"),
            "arm_night": act("armed_night"),
            "trigger": act("triggered"),
        }]})

    def _siren(self, e: dict) -> None:
        # No template siren platform, and the entity registry refuses to rename
        # an entity across domains. So the fake is a template switch that
        # bootstrap-helpers.py wraps with `switch_as_x` into a real siren.*.
        # The `_src` suffix is the contract between the two scripts.
        online = self.online_helper(e)
        state = self.bool_helper(e, False)
        self.template.append({"switch": [{
            "name": f"{e['name']} Src",
            "default_entity_id": f"switch.{slug(e['id'])}_src",
            "unique_id": f"{slug(e['id'])}_src",
            "state": f"{{{{ is_state('{state}','on') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "turn_on": {"action": "input_boolean.turn_on",
                        "target": {"entity_id": state}},
            "turn_off": {"action": "input_boolean.turn_off",
                         "target": {"entity_id": state}},
        }]})

    def _vacuum(self, e: dict) -> None:
        online = self.online_helper(e)
        states = ["docked", "cleaning", "returning", "paused", "idle", "error"]
        mode = self.select_helper(e, states, "docked")
        act = lambda v: {"action": "input_select.select_option",   # noqa: E731
                         "target": {"entity_id": mode},
                         "data": {"option": v}}
        self.template.append({"vacuum": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ states('{mode}') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "start": act("cleaning"),
            "pause": act("paused"),
            "stop": act("idle"),
            "return_to_base": act("returning"),
        }]})

    def _select(self, e: dict) -> None:
        online = self.online_helper(e)
        opts = e["options"]
        mode = self.select_helper(e, opts, e.get("initial", opts[0]))
        self.template.append({"select": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ states('{mode}') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "options": f"{{{{ state_attr('{mode}','options') }}}}",
            "select_option": {"action": "input_select.select_option",
                              "target": {"entity_id": mode},
                              "data": {"option": "{{ option }}"}},
        }]})

    def _sensor(self, e: dict) -> None:
        online = self.online_helper(e)
        init = float(e.get("initial", 0))
        lo, hi = (0, 100) if e.get("device_class") in ("battery", "humidity") else (-50, 10000)
        val = self.num_helper(e, "value", lo, max(hi, init * 2 or hi), 0.1, init)
        cfg = {
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ states('{val}')|float(0) }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
        }
        if e.get("unit"):
            cfg["unit_of_measurement"] = e["unit"]
        if e.get("device_class"):
            cfg["device_class"] = e["device_class"]
        cfg["state_class"] = e.get("state_class", "measurement")
        self.template.append({"sensor": [cfg]})

    def _binary_sensor(self, e: dict) -> None:
        online = self.online_helper(e)
        state = self.bool_helper(e, e.get("initial") == "on")
        if e.get("device_of"):
            # A YAML template cannot join a device, and this one must: it is
            # the motion sensor built into a camera (#29). apply-registry.py
            # builds it as a template helper linked to the camera's device,
            # over these same two backing helpers.
            return
        cfg = {
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": f"{{{{ is_state('{state}','on') }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
        }
        if e.get("device_class"):
            cfg["device_class"] = e["device_class"]
        self.template.append({"binary_sensor": [cfg]})

    def _climate(self, e: dict) -> None:
        # No template climate platform. generic_thermostat is a real climate
        # entity driven by a switch + sensor, both of which we fake.
        online = self.online_helper(e)
        heater = self.bool_helper(e, False)
        temp = self.num_helper(e, "value", 0, 40, 0.1, 20.5)
        sid = slug(e["id"])
        self.template.append({"sensor": [{
            "name": f"{e['name']} Temperatura",
            "default_entity_id": f"sensor.{sid}_temp",
            "unique_id": f"{sid}_temp",
            "state": f"{{{{ states('{temp}')|float(0) }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "unit_of_measurement": "°C",
            "device_class": "temperature",
            "state_class": "measurement",
        }]})
        self.template.append({"switch": [{
            "name": f"{e['name']} Caldaia",
            "default_entity_id": f"switch.{sid}_heater",
            "unique_id": f"{sid}_heater",
            "state": f"{{{{ is_state('{heater}','on') }}}}",
            "turn_on": {"action": "input_boolean.turn_on",
                        "target": {"entity_id": heater}},
            "turn_off": {"action": "input_boolean.turn_off",
                         "target": {"entity_id": heater}},
        }]})
        self.climate.append({
            "platform": "generic_thermostat",
            "name": e["name"],
            "unique_id": sid,
            "heater": f"switch.{sid}_heater",
            "target_sensor": f"sensor.{sid}_temp",
            "min_temp": 5,
            "max_temp": 30,
            "target_temp": 21,
            "cold_tolerance": 0.3,
            "hot_tolerance": 0.3,
            "initial_hvac_mode": "heat",
        })

    def _event(self, e: dict) -> None:
        # A genuine `event` entity: the template platform's trigger-based
        # form, which emits one event per trigger. The trigger is pressing an
        # `input_button`, so a ring is one tap in Home Assistant's UI -- the
        # same entity, state and `event_type` attribute a real Ring ding has
        # (docs/research/ring-integration.md).
        online = self.online_helper(e)
        fire = self.fire_helper(e)
        types = e["event_types"]
        cfg = {
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "event_type": types[0],
            "event_types": f"{{{{ {types!r} }}}}",
            "availability": f"{{{{ is_state('{online}','on') }}}}",
        }
        if e.get("device_class"):
            cfg["device_class"] = e["device_class"]
        self.template.append({
            "triggers": [{"trigger": "state", "entity_id": fire}],
            # A state trigger also fires when the button first appears after
            # a restart (no `from_state`). That is not a press, and a ring on
            # every restart would open the Popup on every restart.
            "conditions": [{"condition": "template",
                            "value_template": "{{ trigger.from_state is not none }}"}],
            "event": [cfg],
        })

    def _button(self, e: dict) -> None:
        # A button reports no state but the time it was last pressed, which
        # the button entity keeps by itself. Pressing the fake does nothing
        # else: the Ring Intercom's `open_door` is fire-and-forget too.
        online = self.online_helper(e)
        self.template.append({"button": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "availability": f"{{{{ is_state('{online}','on') }}}}",
            "press": [],
        }]})

    def _input_button(self, e: dict) -> None:
        # A Page Opener (ADR-0012), which is a helper rather than a fake of a
        # device, so it has no backing helpers and no `fake_online_*`: it
        # holds no state to fake, and the real house creates the same one.
        # Declared on the same path as the `fake_fire_*` buttons, keyed by
        # its object id, which is what makes it `input_button.<id>`.
        self.input_button[e["id"].split(".", 1)[1]] = {"name": e["name"], "icon": e["icon"]}

    def _external(self, e: dict) -> None:
        # A real entity from a real integration (the met.no weather): there
        # is nothing to fake. apply-registry.py only labels it.
        pass

    def _button_lock(self, e: dict) -> None:
        # Not a fake of a device: the wrapper the real house needs too. The
        # Ring Intercom opens its door with a `button` (ring-integration.md),
        # and the panel renders gates as `lock`s and gives `button` no
        # rendering at all, so a template lock stands in front of it.
        #
        # Always `locked`: the Intercom has no state to report, and a door
        # the panel claimed was open would be a guess. Unlocking (or opening)
        # presses the button; locking does nothing, because there is nothing
        # to lock.
        button = e["button"]
        self.template.append({"lock": [{
            "name": e["name"],
            "default_entity_id": e["id"],
            "unique_id": slug(e["id"]),
            "state": "locked",
            # A never-pressed button is `unknown`, which is not a fault here.
            "availability": f"{{{{ not is_state('{button}','unavailable') }}}}",
            "lock": [],
            "unlock": {"action": "button.press", "target": {"entity_id": button}},
            "open": {"action": "button.press", "target": {"entity_id": button}},
        }]})

    def _media_player(self, e: dict) -> None:
        # No template media_player platform. `universal` wraps helpers into a
        # real media_player with the standard service surface.
        online = self.online_helper(e)
        state = self.bool_helper(e, False)
        vol = self.num_helper(e, "level", 0, 1, 0.01, 0.35)
        self.media_player.append({
            "platform": "universal",
            "name": e["name"],
            "unique_id": slug(e["id"]),
            "state_template": (
                f"{{% if not is_state('{online}','on') %}}unavailable"
                f"{{% elif is_state('{state}','on') %}}playing"
                f"{{% else %}}idle{{% endif %}}"
            ),
            "attributes": {"volume_level": vol, "is_volume_muted": state},
            "commands": {
                "turn_on": {"action": "input_boolean.turn_on",
                            "target": {"entity_id": state}},
                "turn_off": {"action": "input_boolean.turn_off",
                             "target": {"entity_id": state}},
                "media_play": {"action": "input_boolean.turn_on",
                               "target": {"entity_id": state}},
                "media_pause": {"action": "input_boolean.turn_off",
                                "target": {"entity_id": state}},
                "volume_set": {"action": "input_number.set_value",
                               "target": {"entity_id": vol},
                               "data": {"value": "{{ volume_level }}"}},
            },
        })

    def _camera(self, e: dict) -> None:
        # The `generic` camera platform is config-flow only in 2026.9 and has
        # no YAML form. A local still image keeps the entity real and in the
        # right Area; live streaming is deliberately out of scope (see #1).
        self.camera.append({
            "platform": "generic",
            "name": e["name"],
            "unique_id": slug(e["id"]),
            "still_image_url": "http://127.0.0.1:8123/local/fake-camera.jpg",
            "verify_ssl": False,
        })


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config-dir", required=True, type=pathlib.Path)
    ap.add_argument("--clean", action="store_true",
                    help="remove generated packages and exit")
    args = ap.parse_args()

    pkg_dir = args.config_dir / "packages"
    if args.clean:
        n = 0
        if pkg_dir.is_dir():
            for f in sorted(pkg_dir.glob(f"{PREFIX}*.yaml")):
                f.unlink()
                n += 1
        print(f"removed {n} generated package(s) from {pkg_dir}")
        return 0

    manifest = yaml.safe_load(MANIFEST.read_text())
    b = Builder(manifest)
    for e in manifest["entities"]:
        b.build(e)

    pkg_dir.mkdir(parents=True, exist_ok=True)

    written = []

    def write(stem: str, payload: dict) -> None:
        path = pkg_dir / f"{PREFIX}{stem}.yaml"
        path.write_text(BANNER + yaml.safe_dump(payload, sort_keys=False,
                                                allow_unicode=True, width=100))
        written.append(path)

    write("helpers", {
        "input_boolean": b.input_boolean,
        "input_number": b.input_number,
        "input_select": b.input_select,
        "input_button": b.input_button,
    })
    write("entities", {"template": b.template})
    if b.media_player:
        write("media_player", {"media_player": b.media_player})
    if b.climate:
        write("climate", {"climate": b.climate})
    if b.camera:
        write("camera", {"camera": b.camera})

    total = len(manifest["entities"])
    helpers = (len(b.input_boolean) + len(b.input_number) + len(b.input_select)
               + len(b.input_button))
    for p in written:
        print(f"wrote {p}")
    print(f"\n{total} fake entities, {helpers} backing helpers")
    print("Next: restart Home Assistant, then run apply-registry.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
